"""The release verifier is pure stdlib; these tests require no VM or Docker."""
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest

spec = importlib.util.spec_from_file_location('release', Path(__file__).parents[1] / 'scripts/verify-demo-release.py')
release = importlib.util.module_from_spec(spec)
spec.loader.exec_module(release)


class VerifyDemoReleaseTests(unittest.TestCase):
    def setUp(self):
        self.folder = tempfile.TemporaryDirectory()
        self.addCleanup(self.folder.cleanup)
        self.root = Path(self.folder.name)
        (self.root / 'Cartoons').mkdir()
        (self.root / 'Cartoons' / 'Approved.mp4').write_bytes(b'synthetic clip')
        self.clip = {
            'path': 'Cartoons/Approved.mp4', 'title': 'Approved', 'creator': 'Fixture author',
            'sourceUrl': 'https://example.com/fixture', 'license': 'Generated test material',
            'modifications': 'Generated by test', 'approvedForPublicDemo': True, 'duration': 3,
        }
        self.metadata = {'version': 2, 'videos': [self.clip]}
        self.save()

    def save(self):
        (self.root / '.demo-media.json').write_text(json.dumps(self.metadata))

    def test_valid_approved_library_returns_inventory(self):
        document, channels = release.stage_inventory(self.root)
        self.assertEqual(document['version'], 2)
        self.assertEqual(dict(channels), {'Cartoons': 1})

    def test_missing_or_unapproved_media_fails_closed(self):
        self.clip['approvedForPublicDemo'] = False
        self.save()
        with self.assertRaisesRegex(ValueError, 'Unapproved'):
            release.stage_inventory(self.root)
        self.clip['approvedForPublicDemo'] = True
        (self.root / 'Cartoons' / 'Approved.mp4').unlink()
        self.save()
        with self.assertRaises(ValueError):
            release.stage_inventory(self.root)

    def test_stale_extra_file_and_private_field_are_rejected(self):
        (self.root / 'Cartoons' / 'stale.mp4').write_bytes(b'fixture')
        with self.assertRaisesRegex(ValueError, 'Stale'):
            release.stage_inventory(self.root)
        (self.root / 'Cartoons' / 'stale.mp4').unlink()
        self.clip['rightsEvidence'] = 'private evidence'
        self.save()
        with self.assertRaisesRegex(ValueError, 'Private'):
            release.stage_inventory(self.root)

    def test_traversal_duplicate_and_wrong_manifest_version_are_rejected(self):
        for entry in ('../Approved.mp4', 'Cartoons/../Approved.mp4', '/tmp/Approved.mp4'):
            self.clip['path'] = entry
            self.save()
            with self.assertRaises(ValueError):
                release.stage_inventory(self.root)
        self.clip['path'] = 'Cartoons/Approved.mp4'
        self.metadata['videos'].append(self.clip.copy())
        self.save()
        with self.assertRaisesRegex(ValueError, 'Duplicate'):
            release.stage_inventory(self.root)
        self.metadata['videos'] = [self.clip]
        self.metadata['version'] = 1
        self.save()
        with self.assertRaises(ValueError):
            release.stage_inventory(self.root)

    def test_rejects_symlinked_files(self):
        (self.root / 'Cartoons' / 'Approved.mp4').unlink()
        (self.root / 'Cartoons' / 'Approved.mp4').symlink_to(self.root / '.demo-media.json')
        with self.assertRaisesRegex(ValueError, 'symlinked'):
            release.stage_inventory(self.root)


if __name__ == '__main__':
    unittest.main()
