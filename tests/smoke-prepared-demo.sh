#!/usr/bin/env bash
# CI-only end-to-end test of an approved, read-only demo-media mount.
set -euo pipefail

workdir="$(mktemp -d)"
cleanup() {
  docker rm -f rabbit-ears-prepared-smoke >/dev/null 2>&1 || true
  rm -rf "$workdir"
}
trap cleanup EXIT
ffmpeg -hide_banner -loglevel error -y \
  -f lavfi -i 'testsrc2=size=320x240:rate=15' \
  -f lavfi -i 'sine=frequency=440:sample_rate=44100' \
  -t 3 -threads 1 -c:v libx264 -pix_fmt yuv420p -c:a aac "$workdir/original.mp4"
cat > "$workdir/manifest.json" <<'JSON'
{
  "version": 2,
  "videos": [{
    "source": "original.mp4",
    "channel": "Verified Test Channel",
    "title": "Generated Test Signal",
    "creator": "Rabbit Ears CI",
    "sourceUrl": "https://example.com/generated-ci-fixture",
    "license": "Generated by automated test, no third-party footage",
    "rightsEvidence": "Created in the current CI run using FFmpeg testsrc2 and sine generators",
    "approvedForPublicDemo": true,
    "reviewedBy": "Rabbit Ears CI (generated fixture only)",
    "reviewedAt": "2026-10-22",
    "modifications": "Generated fixture transcoded to H.264/AAC"
  }]
}
JSON
python3 scripts/prepare-demo-media.py "$workdir/manifest.json" "$workdir/prepared" --validate-only
python3 scripts/prepare-demo-media.py "$workdir/manifest.json" "$workdir/prepared"

docker run -d --name rabbit-ears-prepared-smoke \
  -p 127.0.0.1:8081:8080 \
  -e Box__Demo__RequireApprovedMedia=true \
  -v "$workdir/prepared:/srv/rabbitears/media:ro" rabbit-ears
for i in $(seq 1 30); do
  if curl --fail --silent http://127.0.0.1:8081/api/health >/dev/null; then break; fi
  sleep 1
done
python3 scripts/verify-demo-release.py \
  --base-url http://127.0.0.1:8081 \
  --media-root "$workdir/prepared" \
  --expect-channels 1 \
  --expect-clips 1
