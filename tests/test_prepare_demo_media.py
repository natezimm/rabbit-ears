"""Run with: python3 -m unittest discover -s tests -p 'test_*.py'. Needs ffmpeg."""
import importlib.util
import json
from pathlib import Path
import subprocess
import tempfile
import unittest

spec = importlib.util.spec_from_file_location('prepare', Path(__file__).parents[1] / 'scripts/prepare-demo-media.py')
prepare = importlib.util.module_from_spec(spec)
spec.loader.exec_module(prepare)


class PrepareDemoMediaTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.source = self.root / 'source.mp4'
        self.source.write_text('not a video yet')
        self.output = self.root / 'prepared'
        self.manifest = self.root / 'manifest.json'
        self.video = dict(source='source.mp4', channel='Test channel', title='Episode 1',
                          creator='Test creator', license='Test fixture only',
                          sourceUrl='https://example.com/source', rightsEvidence='Generated by this test')

    def write(self, videos=None):
        self.manifest.write_text(json.dumps(dict(version=1, videos=videos or [self.video])))

    def approved_v2(self):
        self.video.update(modifications='Transcoded without cropping', reviewedBy='QA reviewer',
                          reviewedAt='2026-10-22', approvedForPublicDemo=True)
        return dict(version=2, videos=[self.video])

    def test_v2_rejects_unapproved_and_incomplete_review(self):
        self.manifest.write_text(json.dumps(self.approved_v2()))
        version, videos = prepare.validate(self.manifest, self.output)
        self.assertEqual((version, len(videos)), (2, 1))
        for field, value in [('approvedForPublicDemo', False), ('reviewedBy', ''),
                             ('reviewedAt', 'not a date'), ('modifications', ''),
                             ('licenseUrl', 'javascript:bad'), ('year', 9999),
                             ('sourceUrl', 'https:///bad')]:
            with self.subTest(field=field):
                record = self.video | {field: value}
                self.manifest.write_text(json.dumps(dict(version=2, videos=[record])))
                with self.assertRaises(ValueError):
                    prepare.validate(self.manifest, self.output)

    def test_v2_publishes_attribution_but_never_private_rights_notes(self):
        subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-f', 'lavfi',
                        '-i', 'testsrc2=size=160x120:rate=10', '-t', '1', '-c:v', 'libx264',
                        '-threads', '1', str(self.source)], check=True)
        self.approved_v2()
        self.video.update(licenseUrl='https://example.com/rights', year=1930,
                          attribution='Original creator; licensed copy')
        self.manifest.write_text(json.dumps(dict(version=2, videos=[self.video])))
        prepare.prepare(self.manifest, self.output)
        rendered = (self.output / '.demo-media.json').read_text()
        result = json.loads(rendered)
        self.assertEqual(result['version'], 2)
        self.assertEqual(result['videos'][0]['modifications'], 'Transcoded without cropping')
        self.assertEqual(result['videos'][0]['attribution'], 'Original creator; licensed copy')
        self.assertTrue(result['videos'][0]['approvedForPublicDemo'])
        for sensitive in ('rightsEvidence', 'reviewedBy', 'reviewedAt', 'QA reviewer',
                          'Generated by this test', '"source":'):
            self.assertNotIn(sensitive, rendered)

    def make_video(self, width=160, height=120, length=3, audio=True, sar=None):
        command = ['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y',
                   '-f', 'lavfi', '-i', f'testsrc2=size={width}x{height}:rate=15']
        if audio:
            command += ['-f', 'lavfi', '-i', 'sine=frequency=440:sample_rate=44100']
        command += ['-t', str(length), '-vf', f'setsar={sar}' if sar else 'null',
                    '-c:v', 'libx264', '-threads', '1']
        if audio:
            command += ['-c:a', 'aac']
        command += [str(self.source)]
        subprocess.run(command, check=True)

    def test_trimmed_video_preserves_four_by_three_geometry_and_audio(self):
        self.make_video(width=320, height=240, length=4)
        self.video.update(clipStartSeconds=1, clipDurationSeconds=1.5)
        self.write()
        prepare.prepare(self.manifest, self.output)
        target = self.output / 'Test channel/Episode 1.mp4'
        qa = prepare.inspect_output(target, 1.5, 4 / 3, True)
        self.assertEqual(qa['videoCodec'], 'h264')
        self.assertEqual(qa['pixelFormat'], 'yuv420p')
        self.assertEqual(qa['audioCodec'], 'aac')
        self.assertEqual(qa['sampleAspectRatio'], '1:1')
        self.assertAlmostEqual(qa['duration'], 1.5, delta=0.3)
        metadata = json.loads((self.output / '.demo-media.json').read_text())
        self.assertEqual(metadata['videos'][0]['qa']['width'], qa['width'])
        self.assertEqual(metadata['videos'][0]['encoding'], prepare.ENCODING_VERSION)

    def test_widescreen_can_be_preserved_or_letterboxed_without_stretching(self):
        self.make_video(width=320, height=180, length=2, audio=False)
        self.write()
        prepare.prepare(self.manifest, self.output)
        target = self.output / 'Test channel/Episode 1.mp4'
        first = json.loads((self.output / '.demo-media.json').read_text())['videos'][0]
        self.assertAlmostEqual(first['qa']['width'] / first['qa']['height'], 16 / 9, delta=0.04)
        self.assertIsNone(first['qa']['audioCodec'])
        previous = target.stat().st_mtime_ns
        prepare.prepare(self.manifest, self.output)
        self.assertEqual(target.stat().st_mtime_ns, previous)

        self.video['framing'] = 'letterbox-4:3'
        self.write()
        prepare.prepare(self.manifest, self.output)
        second = json.loads((self.output / '.demo-media.json').read_text())['videos'][0]
        self.assertEqual((second['qa']['width'], second['qa']['height']), (640, 480))
        self.assertNotEqual(first['preparationSha256'], second['preparationSha256'])
        self.assertIsNone(second['qa']['audioCodec'])

    def test_clip_changes_invalidate_cache_even_with_unchanged_source(self):
        self.make_video(length=4)
        self.video.update(clipStartSeconds=0.5, clipDurationSeconds=1)
        self.write()
        prepare.prepare(self.manifest, self.output)
        target = self.output / 'Test channel/Episode 1.mp4'
        original = json.loads((self.output / '.demo-media.json').read_text())['videos'][0]
        first_modified = target.stat().st_mtime_ns
        prepare.prepare(self.manifest, self.output)
        self.assertEqual(target.stat().st_mtime_ns, first_modified)
        self.video['clipStartSeconds'] = 1.5
        self.write()
        prepare.prepare(self.manifest, self.output)
        changed = json.loads((self.output / '.demo-media.json').read_text())['videos'][0]
        self.assertNotEqual(original['preparationSha256'], changed['preparationSha256'])

    def test_invalid_ranges_and_missing_video_are_rejected(self):
        self.make_video(length=2)
        self.write()
        valid = self.manifest
        cases = [
            ('clipStartSeconds', -1), ('clipStartSeconds', float('nan')),
            ('clipDurationSeconds', 0), ('clipDurationSeconds', -1),
            ('clipDurationSeconds', float('inf')), ('framing', 'crop'),
            ('clipStartSeconds', 3), ('clipDurationSeconds', 3),
        ]
        for field, value in cases:
            with self.subTest(field=field, value=value):
                self.video[field] = value
                self.write()
                with self.assertRaises((ValueError, subprocess.CalledProcessError)):
                    prepare.prepare(valid, self.output)
                self.video.pop(field)
        self.source.unlink()
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'lavfi',
                        '-i', 'sine=frequency=440:sample_rate=44100',
                        '-t', '2', str(self.source)], check=True)
        self.write()
        with self.assertRaises((ValueError, subprocess.CalledProcessError)):
            prepare.prepare(self.manifest, self.output)

    def test_anamorphic_pixels_are_normalized(self):
        self.make_video(width=160, height=120, length=2, sar='2/1')
        self.write()
        prepare.prepare(self.manifest, self.output)
        qa = json.loads((self.output / '.demo-media.json').read_text())['videos'][0]['qa']
        self.assertAlmostEqual(qa['width'] / qa['height'], 8 / 3, delta=0.04)
        self.assertEqual(qa['sampleAspectRatio'], '1:1')

    def test_missing_rights_evidence_is_rejected_before_writing(self):
        del self.video['rightsEvidence']
        self.write()
        with self.assertRaises(ValueError):
            prepare.validate(self.manifest, self.output)
        self.assertFalse(self.output.exists())

    def test_traversal_duplicates_and_missing_sources_are_rejected(self):
        for key, value in [('channel', '../escape'), ('title', '.hidden'), ('source', 'missing.mp4')]:
            with self.subTest(key=key):
                self.write([self.video | {key: value}])
                with self.assertRaises(ValueError):
                    prepare.validate(self.manifest, self.output)
        self.write([self.video, self.video.copy()])
        with self.assertRaises(ValueError):
            prepare.validate(self.manifest, self.output)

    def test_symlink_destination_cannot_escape_output(self):
        self.output.mkdir()
        (self.output / 'Test channel').symlink_to(self.root, target_is_directory=True)
        self.write()
        with self.assertRaises(ValueError):
            prepare.validate(self.manifest, self.output)

    def test_encoding_failure_publishes_neither_partial_file_nor_metadata(self):
        self.write()
        with self.assertRaises(subprocess.CalledProcessError):
            prepare.prepare(self.manifest, self.output)
        self.assertFalse((self.output / '.demo-media.json').exists())
        self.assertEqual([], list(self.output.rglob('*.partial')))

    def test_real_encoding_duration_credits_and_repeat_run(self):
        subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-f', 'lavfi',
                        '-i', 'testsrc2=size=160x120:rate=10', '-t', '1', '-c:v', 'libx264',
                        '-threads', '1', str(self.source)], check=True)
        self.write()
        prepare.prepare(self.manifest, self.output)
        target = self.output / 'Test channel/Episode 1.mp4'
        first_write = target.stat().st_mtime_ns
        metadata = json.loads((self.output / '.demo-media.json').read_text())
        self.assertGreater(metadata['videos'][0]['duration'], 0)
        self.assertEqual('Test creator', metadata['videos'][0]['creator'])
        self.assertNotIn('rightsEvidence', metadata['videos'][0])
        data = target.read_bytes()
        self.assertLess(data.index(b'moov'), data.index(b'mdat'))
        prepare.prepare(self.manifest, self.output)
        self.assertEqual(first_write, target.stat().st_mtime_ns)
        (self.output / 'stale.mp4').write_text('stale')
        with self.assertRaises(ValueError):
            prepare.prepare(self.manifest, self.output)


if __name__ == '__main__':
    unittest.main()
